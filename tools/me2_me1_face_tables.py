"""ME2 (2026-11-15): app/me2_src/me2_me1_le1_faces.inc for the LE1 face import (me2_me1_le1.cpp).

An LE1 head morph has LOD0 vertex positions only; ME2's BioMorphFaceSaveObject.LoadObject also takes LOD1 (and LOD2,
which ME1 itself saves unmorphed: equal to the base face). LOD1 is rebuilt from LE1's LOD0 with ME2's own base faces
(BIOG_MORPH_FACE: Player_Base_Female / Player_Base_Male, three vertex buffers each): for every LOD1 vertex the nearest
base LOD0 vertex and the offset between the two, so LOD1[i] = LE1_LOD0[nearest[i]] + offset[i]. Checked on an ME1 Xbox
save (male; its LOD1 vertex order differs from ME2's in places, so compared as point sets): the rebuilt LOD1 lies a mean
0.027 (max 0.50) from ME1's own LOD1, ME2's unchanged base LOD1 0.23 (max 1.5).

The table is derived from the game's data: generated locally, not for publishing (like me2_me1_le1_template.inc).

  python tools/me2_me1_face_tables.py <CookedXenon>/BIOG_MORPH_FACE.xxx app/me2_src/me2_me1_le1_faces.inc
"""
import contextlib
import hashlib
import io
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import me2_package as mp  # noqa: E402

FACES = (('Female', 'Player_Base_Female'), ('Male', 'Player_Base_Male'))


def props_end(p, b, o):
    """End of the tagged properties starting at o (ME2 v512 tags)."""
    def nm(at):
        i, n = struct.unpack_from('>II', b, at)
        return p.names[i] + (f'_{n - 1}' if n else '')
    while True:
        n = nm(o)
        o += 8
        if n == 'None':
            return o
        t = nm(o)
        size = struct.unpack_from('>i', b, o + 8)[0]
        o += 16
        if t == 'StructProperty':
            o += 8
        o += 4 if t == 'BoolProperty' else size


def vertex_buffers(p, b):
    """The native part after the properties: buffer count, then per buffer a bulk array (element size 12, count, xyz)."""
    o = props_end(p, b, 4)
    n = struct.unpack_from('>i', b, o)[0]
    o += 4
    if not 1 <= n <= 8:
        raise ValueError(f'vertex buffer count {n}')
    out = []
    for _ in range(n):
        size, c = struct.unpack_from('>ii', b, o)
        if size != 12:
            raise ValueError(f'vertex element size {size}')
        o += 8
        out.append([struct.unpack_from('>3f', b, o + 12 * j) for j in range(c)])
        o += 12 * c
    return out


def nearest(lod1, lod0):
    try:
        import numpy as np
        a, z = np.array(lod1), np.array(lod0)
        d = ((a[:, None, :] - z[None, :, :]) ** 2).sum(2)
        return [int(i) for i in d.argmin(1)]
    except ImportError:
        return [min(range(len(lod0)), key=lambda k: sum((v[c] - lod0[k][c]) ** 2 for c in range(3))) for v in lod1]


def f32_bits(x):
    return struct.unpack('<I', struct.pack('<f', x))[0]


def main():
    src, dst = sys.argv[1], sys.argv[2]
    data = open(src, 'rb').read()
    with contextlib.redirect_stderr(io.StringIO()):
        raw = mp.decompress(data)
    p = mp.Package(raw)
    lines = [
        '// Generated by tools/me2_me1_face_tables.py from BIOG_MORPH_FACE.xxx (sha256 %s): ME2\'s base faces\' LOD1 as'
        % hashlib.sha256(data).hexdigest()[:16],
        '// (nearest LOD0 vertex, offset) for the LE1 face import in me2_me1_le1.cpp. Game data: not for publishing.',
    ]
    for tag, name in FACES:
        k = next(i for i in range(len(p.exports)) if p.full_name(i + 1) == name)
        e = p.exports[k]
        bufs = vertex_buffers(p, raw[e['offset']:e['offset'] + e['size']])
        lod0, lod1 = bufs[0], bufs[1]
        nn = nearest(lod1, lod0)
        off = [tuple(lod1[i][c] - lod0[nn[i]][c] for c in range(3)) for i in range(len(lod1))]
        far = max((sum(x * x for x in o) ** 0.5 for o in off), default=0)
        print(f'{name}: buffers {[len(x) for x in bufs]}, LOD1 offsets up to {far:.3f}')
        lines.append(f'constexpr uint32_t kFace{tag}Lod0 = {len(lod0)};')
        lines.append(f'constexpr uint32_t kFace{tag}Lod1 = {len(lod1)};')
        lines.append(f'constexpr uint16_t kFace{tag}Nearest[] = {{')
        for j in range(0, len(nn), 16):
            lines.append('  ' + ','.join(str(x) for x in nn[j:j + 16]) + ',')
        lines.append('};')
        lines.append(f'constexpr uint32_t kFace{tag}Offset[] = {{  // float bits, x y z per LOD1 vertex')
        flat = [f32_bits(c) for o in off for c in o]
        for j in range(0, len(flat), 8):
            lines.append('  ' + ','.join('0x%08X' % x for x in flat[j:j + 8]) + ',')
        lines.append('};')
    open(dst, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote', dst)


if __name__ == '__main__':
    main()
